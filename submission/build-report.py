def east(iso):
    if not iso:
        return 'NOT VERIFIED'
    date = datetime.fromisoformat(iso.replace('Z', '+00:00')).astimezone(ZoneInfo('America/New_York'))
    return date.strftime('%b %d, %Y %I:%M %p %Z') + ' (' + iso + ')'

def observation(id, item):
    sample = item.get('observation')
    if not sample:
        return 'NOT VERIFIED. Record values and timestamp after a fresh successful request. Student notes ____________________.'
    if id == 1:
        a, b = sample['comparison']
        return f"{a['id']} ({a['label']}), M {a['x']}, {a['y']} km, versus {b['id']} ({b['label']}), M {b['x']}, {b['y']} km. Both could be centered with the picker. The far side of an orthographic globe is occluded."
    if id == 2:
        return '; '.join(f"{r['countryName']} in {r['time']} had {r['value']:,} people" for r in sample['comparison']) + '.'
    if id == 3:
        return f"Brush included {sample['hours']} hours, from {east(sample['start'])} to {east(sample['end'])}. " + ' '.join(
            f"{label} {r['value']} °C at {east(r['time'])}; wind {r.get('wind', 'unreported')} m/s from {r.get('direction', 'unreported')}°."
            for label, r in zip(['Coolest', 'Warmest'], sample['comparison']))
    if id == 4:
        b = sample['book']
        return f"“{b['label']}” ({b['id']}) pins to {', '.join(a['name'] for a in b['authors'])}. The catalog returned {b['value']} editions and first-publication year {b.get('year', 'unreported')}."
    if id == 5:
        text = f"{sample['distinct']} distinct IDs, {sample['all']} all-category memberships, and {sample['first']} first-category assignments. The scene drew {sample['displayedAll']} dated marks under all and {sample['displayedFirst']} under first."
        if sample['examples']:
            e = sample['examples'][0]
            text += f" {e['id']} had categories {', '.join(e['categories'])}."
        return text
    if id == 6:
        e = sample['event']
        return f"{e['id']} (M {e['x']}, depth {e['y']} km) stayed pinned across swarm and bins. All {sample['brushedCount']} selected IDs survived the layout change, including {', '.join(sample['exampleBrushedIds'])}."
    if id == 7:
        a, b = sample['comparison']
        return f"{a['countryName']} moved from {a['value']}% in {a['time']} to {b['value']}% in {b['time']}. The selected pair crossed from positive to negative growth and appeared in the lower-right quadrant."
    return ' '.join(f"{r['city']} forecast {r['value']} mm for {east(r['time'])}." for r in sample['comparison'])

