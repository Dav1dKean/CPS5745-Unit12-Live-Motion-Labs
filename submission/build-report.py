def html_block(block):
    kind, value = block
    if kind == 'img':
        path, caption = value
        return f'<figure><img src="{escape(path)}" alt="{escape(caption)}"><figcaption>{escape(caption)}</figcaption></figure>'
    tag = 'h2' if kind == 'h' else 'p'
    escaped = escape(value)
    escaped = re.sub(r'(https?://\S+)', lambda m: f'<a href="{m[0]}">{m[0]}</a>', escaped)
    return f'<{tag}>{escaped}</{tag}>'

