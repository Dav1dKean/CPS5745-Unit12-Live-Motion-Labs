rels, image_files = [], []
def paragraph(text, style=None):
    props = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ''
    return f'<w:p>{props}<w:r><w:t xml:space="preserve">{escape(text)}</w:t></w:r></w:p>'

def image(path, caption):
    data = (HERE / path).read_bytes()
    width, height = unpack('>II', data[16:24])
    scale = min(6.6 * 914400 / width, 3.55 * 914400 / height)
    cx, cy = round(width * scale), round(height * scale)
    i = len(image_files) + 1
    name = f'image{i}.png'
    image_files.append((name, data))
    rels.append(f'<Relationship Id="pic{i}" Type="{R}/image" Target="media/{name}"/>')
    caption_xml = escape(caption, quote=True)
    return f'''<w:p><w:r><w:drawing><wp:inline><wp:extent cx="{cx}" cy="{cy}"/><wp:docPr id="{i}" name="Screenshot {i}" descr="{caption_xml}"/>
    <a:graphic><a:graphicData uri="{PIC}"><pic:pic><pic:nvPicPr><pic:cNvPr id="{i}" name="{name}"/><pic:cNvPicPr/></pic:nvPicPr>
    <pic:blipFill><a:blip r:embed="pic{i}"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>
    <pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr></pic:pic></a:graphicData></a:graphic>
    </wp:inline></w:drawing></w:r></w:p>''' + paragraph(caption, 'Caption')

